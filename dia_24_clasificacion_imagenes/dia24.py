# Usar TensorFlow Datasets (más fácil que Kaggle)
dataset, info = tfds.load(
    'cats_vs_dogs',
    split=['train[:80%]', 'train[80%:]'],
    as_supervised=True,
    with_info=True
)

train_dataset, test_dataset = dataset

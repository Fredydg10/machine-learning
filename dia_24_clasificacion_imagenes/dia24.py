# 4. Modelo 1: CNN desde cero
print("\n" + "="*70)
print(" MODELO 1: CNN DESDE CERO")
print("="*70)

print("""
Arquitectura:
Input (128, 128, 3)
    ↓
Conv2D(32, 3x3) + ReLU + BatchNorm
    ↓
MaxPooling2D(2x2)
    ↓
Conv2D(64, 3x3) + ReLU + BatchNorm
    ↓
MaxPooling2D(2x2)
    ↓
Conv2D(128, 3x3) + ReLU + BatchNorm
    ↓
MaxPooling2D(2x2)
    ↓
GlobalAveragePooling2D
    ↓
Dense(128) + ReLU + Dropout(0.5)
    ↓
Dense(1) + Sigmoid
""")

cnn_from_scratch = Sequential([
    Input(shape=(IMG_SIZE, IMG_SIZE, 3)),

    # Bloque 1
    Conv2D(32, (3, 3), activation='relu', padding='same'),
    BatchNormalization(),
    MaxPooling2D((2, 2)),

    # Bloque 2
    Conv2D(64, (3, 3), activation='relu', padding='same'),
    BatchNormalization(),
    MaxPooling2D((2, 2)),

    # Bloque 3
    Conv2D(128, (3, 3), activation='relu', padding='same'),
    BatchNormalization(),
    MaxPooling2D((2, 2)),

    # Clasificador
    GlobalAveragePooling2D(),
    Dense(128, activation='relu'),
    Dropout(0.5),
    Dense(1, activation='sigmoid')
])

cnn_from_scratch.summary()

# Compilar
cnn_from_scratch.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

# Callbacks
early_stopping = EarlyStopping(
    monitor='val_loss',
    patience=5,
    restore_best_weights=True
)

reduce_lr = ReduceLROnPlateau(
    monitor='val_loss',
    factor=0.5,
    patience=3,
    min_lr=1e-6
)

# Entrenar
print("\n🚀 Entrenando CNN desde cero...")
history_cnn = cnn_from_scratch.fit(
    train_dataset,
    validation_data=test_dataset,
    epochs=20,
    callbacks=[early_stopping, reduce_lr],
    verbose=1
)


# 5. Modelo 2: Transfer Learning
print("\n" + "="*70)
print(" Modelo 2: Transfer Learning (MobileNetV2)")
print("="*70)

print(" Descargando MobileNetV2 pre-entrenado...")
base_model = MobileNetV2(
    input_shape=(IMG_SIZE, IMG_SIZE, 3),
    include_top=False,
    weights='imagenet'
)
base_model.trainable = False

print(" Base model cargado")

# Construir modelo
transfer_model = Sequential([
    Input(shape=(IMG_SIZE, IMG_SIZE, 3)),
    data_augmentation,
    base_model,
    GlobalAveragePooling2D(),
    Dropout(0.2),
    Dense(1, activation='sigmoid')
])

transfer_model.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

transfer_model.summary()

# Entrenar
print("\n Entrenando con Transfer Learning...")
history_transfer = transfer_model.fit(
    train_dataset,
    validation_data=test_dataset,
    epochs=15,
    callbacks=[early_stopping, reduce_lr],
    verbose=1
)



# 3. Preprocesamiento y data augmentation
print("\n" + "="*70)
print(" Preprocesamiento y data augmentation")
print("="*70)

IMG_SIZE = 128
BATCH_SIZE = 32

# Función para redimensionar y normalizar
def preprocess(image, label):
    image = tf.cast(image, tf.float32) / 255.0
    image = tf.image.resize(image, [IMG_SIZE, IMG_SIZE])
    return image, label

# Data Augmentation (solo para entrenamiento)
data_augmentation = Sequential([
    tf.keras.layers.RandomFlip("horizontal"),
    tf.keras.layers.RandomRotation(0.1),
    tf.keras.layers.RandomZoom(0.1),
    tf.keras.layers.RandomContrast(0.1),
])

# Preparar datasets
train_dataset = (
    train_dataset
    .map(preprocess, num_parallel_calls=tf.data.AUTOTUNE)
    .cache()
    .shuffle(1000)
    .batch(BATCH_SIZE)
    .prefetch(tf.data.AUTOTUNE)
)

test_dataset = (
    test_dataset
    .map(preprocess, num_parallel_calls=tf.data.AUTOTUNE)
    .batch(BATCH_SIZE)
    .prefetch(tf.data.AUTOTUNE)
)

print(f"\n✅ Datasets preparados")
print(f"   Image size: {IMG_SIZE}x{IMG_SIZE}")
print(f"   Batch size: {BATCH_SIZE}")

# Visualizar ejemplos
fig, axes = plt.subplots(2, 5, figsize=(12, 5))

# ✅ CORRECCIÓN: Agregamos .unbatch() para obtener imágenes individuales, no lotes
for idx, (image, label) in enumerate(train_dataset.unbatch().take(10)):
    ax = axes[idx // 5, idx % 5]
    ax.imshow(image)
    ax.set_title(f'{"🐱 Gato" if label == 0 else "🐶 Perro"}', fontsize=10, fontweight='bold')
    ax.axis('off')

plt.suptitle('📊 Dataset Cats vs Dogs', fontsize=14, fontweight='bold')
